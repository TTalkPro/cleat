using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Cleat.Compiler.Generators;

/// <summary>
/// IR 节点的样板代码（cleat-171，designs/30 §2 D3）。对每个标了 <c>[Node(Langs…)]</c> 的 <c>sealed partial class</c>，按它声明的
/// 公开只读实例字段（声明顺序）生成：构造器、<c>Kind</c> / <c>Langs</c>、<c>Update</c>（字段都没变就返回自己，否则新节点并复制源位置）、
/// <c>Rewriter</c> / <c>Walker</c> 的接受方法；再生成 <c>NodeKind</c> 枚举与 <c>Rewriter</c> / <c>Walker</c> 的缺省访问方法（递归子节点）。
/// 字段分三种：类型派生自 <c>Node</c> 的是子节点；<c>ImmutableArray&lt;T&gt;</c> 且 T 派生自 <c>Node</c> 的是子节点表；其余是终结符（原样复制）。
/// </summary>
[Generator]
public sealed class NodeGenerator : IIncrementalGenerator
{
    private const string AttributeName = "Cleat.Compiler.Ir.NodeAttribute";
    private const string NodeBase = "Cleat.Compiler.Ir.Node";

    private enum FieldKind { Child, ChildList, Terminal }

    private sealed class FieldInfo
    {
        public string Name, Type, ElementType;
        public FieldKind Kind;
    }

    private sealed class NodeInfo
    {
        public string Namespace, Name;
        public int Langs;
        public List<FieldInfo> Fields = new List<FieldInfo>();
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var nodes = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeName,
            static (node, _) => node is Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax,
            static (ctx, _) => Describe((INamedTypeSymbol)ctx.TargetSymbol, ctx.Attributes))
            .Where(static n => n != null);
        context.RegisterSourceOutput(nodes, static (spc, n) => spc.AddSource(n.Name + ".g.cs", EmitNode(n)));
        context.RegisterSourceOutput(nodes.Collect(), static (spc, all) =>
        {
            var sorted = all.OrderBy(n => n.Name, System.StringComparer.Ordinal).ToList();
            if (sorted.Count > 0) spc.AddSource("Visitors.g.cs", EmitVisitors(sorted));
        });
    }

    private static NodeInfo Describe(INamedTypeSymbol type, ImmutableArray<AttributeData> attrs)
    {
        var info = new NodeInfo
        {
            Namespace = type.ContainingNamespace.ToDisplayString(),
            Name = type.Name,
            Langs = attrs.Length > 0 && attrs[0].ConstructorArguments.Length > 0 && attrs[0].ConstructorArguments[0].Value is int v ? v : 0,
        };
        foreach (var m in type.GetMembers())
        {
            if (m is not IFieldSymbol f || f.IsStatic || f.IsImplicitlyDeclared || !f.IsReadOnly || f.DeclaredAccessibility != Accessibility.Public) continue;
            var fi = new FieldInfo { Name = f.Name, Type = f.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), Kind = FieldKind.Terminal };
            if (IsNode(f.Type)) fi.Kind = FieldKind.Child;
            else if (f.Type is INamedTypeSymbol nt && nt.IsGenericType && nt.ConstructedFrom.ToDisplayString() == "System.Collections.Immutable.ImmutableArray<T>"
                     && IsNode(nt.TypeArguments[0]))
            {
                fi.Kind = FieldKind.ChildList;
                fi.ElementType = nt.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            }
            info.Fields.Add(fi);
        }
        // 字段按源码声明顺序（GetMembers 对同一 partial 部分即声明顺序；多部分时按位置排序以求确定）
        info.Fields = info.Fields
            .Select(fi => (fi, loc: type.GetMembers(fi.Name).First().Locations.FirstOrDefault()))
            .OrderBy(t => t.loc?.SourceTree?.FilePath ?? "", System.StringComparer.Ordinal)
            .ThenBy(t => t.loc?.SourceSpan.Start ?? 0)
            .Select(t => t.fi).ToList();
        return info;
    }

    private static bool IsNode(ITypeSymbol t)
    {
        for (var b = t; b != null; b = b.BaseType)
            if (b.ToDisplayString() == NodeBase) return true;
        return false;
    }

    private static string Param(string field)
    {
        string p = char.ToLowerInvariant(field[0]) + field.Substring(1);
        return SyntaxFacts.GetKeywordKind(p) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(p) != SyntaxKind.None ? "@" + p : p;
    }

    private static string EmitNode(NodeInfo n)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> cleat-171 NodeGenerator");
        sb.AppendLine("#nullable disable");
        sb.AppendLine($"namespace {n.Namespace};");
        sb.AppendLine();
        sb.AppendLine($"partial class {n.Name}");
        sb.AppendLine("{");
        string ps = string.Join(", ", n.Fields.Select(f => $"{f.Type} {Param(f.Name)}"));
        string args = string.Join(", ", n.Fields.Select(f => Param(f.Name)));
        sb.AppendLine($"    public {n.Name}({ps})");
        sb.AppendLine("    {");
        foreach (var f in n.Fields) sb.AppendLine($"        {f.Name} = {Param(f.Name)};");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    public override global::Cleat.Compiler.Ir.NodeKind Kind => global::Cleat.Compiler.Ir.NodeKind.{n.Name};");
        sb.AppendLine($"    public override global::Cleat.Compiler.Ir.Langs Langs => (global::Cleat.Compiler.Ir.Langs){n.Langs};");
        sb.AppendLine();
        if (n.Fields.Count > 0)
        {
            string same = string.Join(" && ", n.Fields.Select(f => f.Kind == FieldKind.Terminal
                ? $"global::System.Collections.Generic.EqualityComparer<{f.Type}>.Default.Equals({Param(f.Name)}, {f.Name})"
                : f.Kind == FieldKind.Child ? $"ReferenceEquals({Param(f.Name)}, {f.Name})" : $"{Param(f.Name)} == {f.Name}"));
            sb.AppendLine("    /// <summary>字段都没变时返回自己，否则建新节点（复制源位置）。</summary>");
            sb.AppendLine($"    public {n.Name} Update({ps}) =>");
            sb.AppendLine($"        {same} ? this : CopyPosTo(new {n.Name}({args}));");
            sb.AppendLine();
        }
        sb.AppendLine($"    internal override global::Cleat.Compiler.Ir.Node AcceptRewriter(global::Cleat.Compiler.Ir.Rewriter r) => r.Visit{n.Name}(this);");
        sb.AppendLine($"    internal override void AcceptWalker(global::Cleat.Compiler.Ir.Walker w) => w.Visit{n.Name}(this);");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string EmitVisitors(List<NodeInfo> all)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> cleat-171 NodeGenerator");
        sb.AppendLine("#nullable disable");
        sb.AppendLine("namespace Cleat.Compiler.Ir;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>全部 IR 节点种类（生成）。</summary>");
        sb.AppendLine("public enum NodeKind");
        sb.AppendLine("{");
        foreach (var n in all) sb.AppendLine($"    {n.Name},");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("partial class Rewriter");
        sb.AppendLine("{");
        foreach (var n in all)
        {
            string q = $"global::{n.Namespace}.{n.Name}";
            if (n.Fields.Count == 0) { sb.AppendLine($"    public virtual Node Visit{n.Name}({q} n) => n;"); continue; }
            string a = string.Join(", ", n.Fields.Select(f => f.Kind switch
            {
                FieldKind.Child => $"Rewrite(n.{f.Name})",
                FieldKind.ChildList => $"RewriteList(n.{f.Name})",
                _ => $"n.{f.Name}",
            }));
            sb.AppendLine($"    public virtual Node Visit{n.Name}({q} n) => n.Update({a});");
        }
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("partial class Walker");
        sb.AppendLine("{");
        foreach (var n in all)
        {
            string q = $"global::{n.Namespace}.{n.Name}";
            var kids = n.Fields.Where(f => f.Kind != FieldKind.Terminal).ToList();
            if (kids.Count == 0) { sb.AppendLine($"    public virtual void Visit{n.Name}({q} n) {{ }}"); continue; }
            sb.AppendLine($"    public virtual void Visit{n.Name}({q} n)");
            sb.AppendLine("    {");
            foreach (var f in kids) sb.AppendLine(f.Kind == FieldKind.Child ? $"        Walk(n.{f.Name});" : $"        WalkList(n.{f.Name});");
            sb.AppendLine("    }");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }
}
