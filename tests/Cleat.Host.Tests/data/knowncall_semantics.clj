;; argument order: function value first, then arguments left to right
(def order (atom []))
(defn f3 [a b c] [a b c])
(defn ord [] (f3 (do (swap! order conj :a) 1) (do (swap! order conj :b) 2) (do (swap! order conj :c) 3)))
(show (ord) @order)
;; a long lazy sequence passed to a known function is not held by the caller's temporaries
(defn cnt [s] (loop [s (seq s) n 0] (if s (recur (next s) (inc n)) n)))
(defn count-range [n] (cnt (map inc (range n))))
(show (count-range 3000000))
