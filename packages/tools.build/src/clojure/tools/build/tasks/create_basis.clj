;; cleat port (designs/18 §3): the basis comes from the project's cleat.edn;
;; NuGet deps are resolved by `dotnet restore` (nuget.config decides sources and
;; credentials, so private feeds such as BaGetter work), :local/root deps are
;; other cleat projects. Upstream wraps tools.deps' create-basis.

(ns clojure.tools.build.tasks.create-basis
  (:require
    [clojure.edn :as edn]
    [clojure.set]
    [clojure.string :as str]
    [clojure.tools.build.api :as api]
    [clojure.tools.build.util.file :as file])
  (:import
    [System.IO Directory File Path]
    [System.Text.Json JsonDocument JsonElement JsonValueKind]))

(def ^:private runtime-package
  "The runtime package: the cleat running the program provides it, so it and
  the packages only it depends on stay off the load path."
  "Cleat.Runtime")

(defn default-local-feed
  "The local NuGet feed (designs/18 §6): $CLEAT_LOCAL_FEED, else ~/.cleat/local-feed."
  ^String []
  (or (some-> (System.Environment/GetEnvironmentVariable "CLEAT_LOCAL_FEED") str/trim not-empty)
      (Path/Combine (System.Environment/GetFolderPath System.Environment+SpecialFolder/UserProfile) ".cleat" "local-feed")))

;;; cleat.edn

(defn- read-edn-file [^String path]
  (if (File/Exists path)
    (or (edn/read-string (slurp path)) {})
    {}))

(defn- merge-edn
  "Merge cleat.edn maps: :deps and :aliases merge, other keys are replaced."
  [a b]
  (merge-with (fn [x y] (if (and (map? x) (map? y)) (merge x y) y)) a b))

(defn- merge-args
  [a b]
  (merge-with (fn [x y] (if (and (sequential? x) (sequential? y)) (into (vec x) y) y)) a b))

(defn- apply-aliases
  "Apply the aliases' :replace-paths / :replace-deps / :extra-paths /
  :extra-deps to edn; returns [edn extra-paths argmap]."
  [edn aliases]
  (reduce
    (fn [[edn extra argmap] alias]
      (let [a (get-in edn [:aliases alias])]
        (when (and (some? alias) (nil? a) (not (contains? (:aliases edn) alias)))
          (throw (ex-info (str "Unknown alias " alias) {:alias alias})))
        [(cond-> edn
           (contains? a :replace-paths) (assoc :paths (vec (:replace-paths a)))
           (contains? a :replace-deps) (assoc :deps (:replace-deps a))
           (:extra-deps a) (update :deps merge (:extra-deps a)))
         (into extra (:extra-paths a))
         (merge-args argmap (dissoc a :replace-paths :replace-deps :extra-paths :extra-deps))]))
    [edn [] {}]
    aliases))

(defn- nuget-coord? [coord] (contains? coord :nuget/version))
(defn- local-coord? [coord] (contains? coord :local/root))

(defn- collect-deps
  "Walk deps, following :local/root projects; returns {:local [[lib info]...]
  :nuget {lib version}} (first occurrence of a lib wins, as nearest-first)."
  [deps ^String base-dir]
  (loop [queue (vec (map (fn [[lib coord]] [lib coord base-dir]) deps))
         seen #{}
         local []
         nuget {}]
    (if-let [[lib coord dir] (first queue)]
      (let [queue (subvec queue 1)]
        (cond
          (contains? seen lib) (recur queue seen local nuget)

          (nuget-coord? coord)
          (recur queue (conj seen lib) local (assoc nuget lib (str (:nuget/version coord))))

          (local-coord? coord)
          (let [root (Path/GetFullPath (Path/Combine dir (str (:local/root coord))))
                edn (read-edn-file (Path/Combine root "cleat.edn"))
                paths (mapv #(Path/GetFullPath (Path/Combine root (str %))) (or (:paths edn) ["src"]))]
            (when-not (Directory/Exists root)
              (throw (ex-info (str "Local dep " lib " not found: " root) {:lib lib :local/root root})))
            (recur (into queue (map (fn [[l c]] [l c root]) (:deps edn)))
                   (conj seen lib)
                   (conj local [lib {:local/root root :paths paths}])
                   nuget))

          :else
          (throw (ex-info (str "Unsupported dep coordinate for " lib ": " (pr-str coord)
                               " (cleat supports :nuget/version and :local/root)")
                          {:lib lib :coord coord}))))
      {:local local :nuget nuget})))

;;; NuGet restore

(defn- xml-escape [s]
  (-> (str s) (str/replace "&" "&amp;") (str/replace "<" "&lt;") (str/replace ">" "&gt;") (str/replace "\"" "&quot;")))

(defn- restore-project
  [nuget]
  (str "<Project Sdk=\"Microsoft.NET.Sdk\">\n"
       "  <!-- generated by clojure.tools.build create-basis: the project's NuGet deps, for dotnet restore -->\n"
       "  <PropertyGroup>\n"
       "    <TargetFramework>net10.0</TargetFramework>\n"
       "    <OutputType>Library</OutputType>\n"
       "    <EnableDefaultItems>false</EnableDefaultItems>\n"
       "  </PropertyGroup>\n"
       "  <ItemGroup>\n"
       (apply str (for [[lib version] (sort-by (comp str key) nuget)]
                    (str "    <PackageReference Include=\"" (xml-escape lib) "\" Version=\"" (xml-escape version) "\" />\n")))
       "  </ItemGroup>\n"
       "</Project>\n"))

(def ^:private isolation-files
  "Files next to the generated project, so that a surrounding repository's
  Directory.Build.* or central package management do not apply to it."
  {"Directory.Build.props" "<Project />\n"
   "Directory.Build.targets" "<Project />\n"
   "Directory.Packages.props" "<Project><PropertyGroup><ManagePackageVersionsCentrally>false</ManagePackageVersionsCentrally></PropertyGroup></Project>\n"})

(defn- sha256 [^String s]
  (Convert/ToHexString (System.Security.Cryptography.SHA256/HashData (.GetBytes System.Text.Encoding/UTF8 s))))

(defn- restore!
  "dotnet restore the deps in <root>/.cleat/basis; returns the assets file
  path. Skipped when the deps (and the local feed) are unchanged."
  [^String root nuget ^String local-feed]
  (let [dir (Path/Combine root ".cleat" "basis")
        csproj (Path/Combine dir "restore.csproj")
        assets (Path/Combine dir "obj" "project.assets.json")
        stamp (Path/Combine dir "restore.sha256")
        project-text (restore-project nuget)
        feed? (Directory/Exists local-feed)
        hash (sha256 (str project-text "\n" (when feed? local-feed)))]
    (file/ensure-dir dir)
    (doseq [[name text] isolation-files]
      (spit (Path/Combine dir name) text))
    (when-not (and (File/Exists assets) (File/Exists stamp) (= hash (str/trim (slurp stamp))))
      (spit csproj project-text)
      (when (File/Exists stamp) (File/Delete stamp))
      (let [{:keys [exit out err]}
            (api/process {:command-args (cond-> ["dotnet" "restore" csproj "-nologo" "-v" "q"]
                                          feed? (conj (str "-p:RestoreAdditionalProjectSources=" local-feed)))
                          :dir root
                          :out :capture :err :capture
                          :env {"DOTNET_CLI_TELEMETRY_OPTOUT" "1" "DOTNET_NOLOGO" "1"}})]
        (when-not (zero? exit)
          (throw (ex-info (str "dotnet restore failed for the project's NuGet deps:\n" (str/join "\n" (remove nil? [out err])))
                          {:exit exit :out out :err err :project csproj}))))
      (spit stamp hash))
    assets))

(defn- props
  "The [name value] pairs of a JSON object (none for anything else)."
  [e]
  (if (and e (= JsonValueKind/Object (.ValueKind ^JsonElement e)))
    (map (fn [^System.Text.Json.JsonProperty p] [(.Name p) (.Value p)]) (.EnumerateObject ^JsonElement e))
    []))

(defn- prop
  "The value of a JSON object's property, or nil."
  [^JsonElement e ^String name]
  (some (fn [[k v]] (when (= k name) v)) (props e)))

(defn- read-assets
  "Read project.assets.json: {id {:version v, :dir package-dir,
  :runtime [relative paths], :dependencies #{id}}}"
  [^String assets]
  (with-open [doc (JsonDocument/Parse ^String (slurp assets) (System.Text.Json.JsonDocumentOptions.))]
    (let [root (.RootElement doc)
          folder (first (first (props (prop root "packageFolders"))))
          libraries (into {} (props (prop root "libraries")))
          target (second (first (props (prop root "targets"))))]
      (into {}
        (for [[key lib] (props target)
              :when (= "package" (some-> (prop lib "type") .GetString))
              :let [[id version] (str/split key #"/" 2)
                    rel (.GetString ^JsonElement (prop (get libraries key) "path"))]]
          [id {:version version
               :dir (Path/Combine folder rel)
               :runtime (->> (props (prop lib "runtime"))
                             (map first)
                             (remove #(str/ends-with? % "_._"))
                             vec)
               :dependencies (set (map first (props (prop lib "dependencies"))))}])))))

(defn- reachable
  "Package ids reachable from start along :dependencies, not passing through
  the ids in stop."
  [pkgs start stop]
  (loop [todo [start] seen #{}]
    (if-let [id (first todo)]
      (if (or (seen id) (and (stop id) (not= id start)))
        (recur (rest todo) seen)
        (recur (concat (rest todo) (get-in pkgs [id :dependencies])) (conj seen id)))
      seen)))

(defn- runtime-only
  "Ids of the runtime package and the packages reachable only through it."
  [pkgs top-level]
  (if (contains? pkgs runtime-package)
    (clojure.set/difference
      (reachable pkgs runtime-package #{})
      (apply clojure.set/union #{}
        (map #(reachable pkgs % #{runtime-package}) (remove #(= % runtime-package) top-level))))
    #{}))

(defn- nuget-libs
  [root nuget local-feed]
  (if (empty? nuget)
    []
    (let [pkgs (read-assets (restore! root nuget local-feed))
          by-lower (into {} (map (fn [[id v]] [(str/lower-case id) id]) pkgs))
          top-level (keep #(get by-lower (str/lower-case (str %))) (keys nuget))
          skip (runtime-only pkgs top-level)
          lib-sym (fn [id] (or (first (filter #(= (str/lower-case (str %)) (str/lower-case id)) (keys nuget)))
                               (symbol id)))
          dependents (reduce-kv (fn [m id {:keys [dependencies]}]
                                  (reduce #(update %1 (get by-lower (str/lower-case %2) %2) (fnil conj []) (lib-sym id)) m dependencies))
                                {} pkgs)]
      (->> pkgs
           (remove (fn [[id _]] (contains? skip id)))
           (sort-by (comp str/lower-case key))
           (mapv (fn [[id {:keys [version dir runtime]}]]
                   [(lib-sym id)
                    (cond-> {:nuget/version version
                             :nuget/id id
                             :paths (->> runtime
                                         (map #(Path/GetDirectoryName (Path/GetFullPath (Path/Combine dir %))))
                                         distinct vec)}
                      (seq (dependents id)) (assoc :dependents (vec (dependents id))))]))))))

(defn create-basis
  "Create a basis from cleat.edn (designs/18 §3).

    Options (note, paths resolved via *project-root*):
    :project - cleat.edn path or map, default = \"cleat.edn\"
    :extra   - map merged over the project
    :aliases - coll of aliases
    :local-feed - local NuGet feed dir"
  ([]
   (create-basis nil))
  ([{:keys [project extra aliases local-feed] :or {project "cleat.edn"} :as _params}]
   (let [root (Path/GetFullPath (api/resolve-path "."))
         edn (merge-edn (if (map? project) project (read-edn-file (Path/GetFullPath (api/resolve-path project))))
                        (or extra {}))
         ;; :paths entries may name aliases whose values are paths (as in deps.edn)
         edn (update edn :paths (fn [ps] (vec (mapcat #(if (keyword? %) (get-in edn [:aliases %]) [%]) (or ps ["src"])))))
         [edn extra-paths argmap] (apply-aliases edn aliases)
         {:keys [local nuget]} (collect-deps (:deps edn) root)
         ;; NuGet deps of the local projects join the restore
         libs (into (vec local) (nuget-libs root nuget (or local-feed (default-local-feed))))
         paths (vec (concat (:paths edn) extra-paths))
         roots (vec (distinct (concat paths (mapcat (comp :paths second) libs))))]
     (assoc edn
       :argmap argmap
       :libs (into {} libs)
       :classpath (merge (into {} (map (fn [p] [p {:path-key :paths}]) (:paths edn)))
                         (into {} (map (fn [p] [p {:path-key :extra-paths}]) extra-paths))
                         (into {} (for [[lib {:keys [paths]}] libs, p paths] [p {:lib-name lib}])))
       :classpath-roots roots))))
