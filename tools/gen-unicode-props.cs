#!/usr/bin/env dotnet
// 生成 src/Cleat.Scheme/Runtime/UnicodeProperties.cs（skeg iron-072，cleat-077 纳入）：R6RS 的 char-alphabetic? / char-upper-case? /
// char-lower-case? 按 Unicode 的 Alphabetic / Uppercase / Lowercase 派生属性定义，而 .NET 的 char.IsLetter /
// IsUpper / IsLower 只看一般类别。差集（Other_Alphabetic、Other_Uppercase、Other_Lowercase）来自 UCD 的 PropList.txt，
// 这里生成为区间表（不含 .NET 已覆盖的 L* / Lu / Ll）。
//   dotnet run tools/gen-unicode-props.cs -- <PropList.txt 路径> [输出路径]   （在仓库根目录运行）
// PropList.txt 不入库（Chez 的 unicode/UNIDATA 目录或 unicode.org 的 UCD 都有）。
using System.Text;

if (args.Length is 0 or > 2) { Console.Error.WriteLine("usage: gen-unicode-props.cs <PropList.txt> [输出 .cs]"); return 1; }
var lines = File.ReadAllLines(args[0]);
string version = lines.FirstOrDefault(l => l.StartsWith("# PropList-"))?.Substring("# PropList-".Length).Replace(".txt", "") ?? "?";
var props = new[] { "Other_Alphabetic", "Other_Uppercase", "Other_Lowercase" };
var sb = new StringBuilder();
sb.AppendLine("// <auto-generated/> tools/gen-unicode-props.cs 从 UCD PropList.txt 生成（Unicode " + version + "），勿手改。");
sb.AppendLine("// R6RS 11.11：char-alphabetic? / char-upper-case? / char-lower-case? 按 Alphabetic / Uppercase / Lowercase 属性；");
sb.AppendLine("// 它们等于一般类别 L* / Lu / Ll 加上这里的 Other_* 区间（Alphabetic 另加 Nl），见 HostPrimitives.cs。");
sb.AppendLine();
sb.AppendLine("namespace Cleat.Scheme;");
sb.AppendLine();
sb.AppendLine("internal static class UnicodeProperties");
sb.AppendLine("{");
foreach (var p in props)
{
    var ranges = new List<(int, int)>();
    foreach (var l in lines)
    {
        int semi = l.IndexOf(';'); if (semi < 0) continue;
        var prop = l.Substring(semi + 1).Split('#')[0].Trim();
        if (prop != p) continue;
        var cp = l.Substring(0, semi).Trim().Split("..");
        int lo = Convert.ToInt32(cp[0], 16), hi = cp.Length > 1 ? Convert.ToInt32(cp[1], 16) : lo;
        if (ranges.Count > 0 && ranges[^1].Item2 + 1 == lo) ranges[^1] = (ranges[^1].Item1, hi); else ranges.Add((lo, hi));
    }
    sb.AppendLine($"    /// <summary>{p}：{ranges.Count} 个区间，[起, 止] 成对。</summary>");
    sb.AppendLine($"    public static readonly int[] {p.Replace("_", "")} =");
    sb.AppendLine("    {");
    for (int i = 0; i < ranges.Count; i += 6)
        sb.AppendLine("        " + string.Join(" ", ranges.Skip(i).Take(6).Select(r => $"0x{r.Item1:X4}, 0x{r.Item2:X4},")));
    sb.AppendLine("    };");
    sb.AppendLine();
}
sb.AppendLine("    /// <summary>码点是否落在区间表中（二分）。</summary>");
sb.AppendLine("    public static bool Contains(int[] table, int cp)");
sb.AppendLine("    {");
sb.AppendLine("        int lo = 0, hi = table.Length / 2 - 1;");
sb.AppendLine("        while (lo <= hi)");
sb.AppendLine("        {");
sb.AppendLine("            int mid = (lo + hi) >> 1;");
sb.AppendLine("            if (cp < table[2 * mid]) hi = mid - 1;");
sb.AppendLine("            else if (cp > table[2 * mid + 1]) lo = mid + 1;");
sb.AppendLine("            else return true;");
sb.AppendLine("        }");
sb.AppendLine("        return false;");
sb.AppendLine("    }");
sb.AppendLine("}");
var outPath = args.Length > 1 ? args[1] : "src/Cleat.Scheme/Runtime/UnicodeProperties.cs";   // 在仓库根目录运行
File.WriteAllText(outPath, sb.ToString());
Console.WriteLine($"wrote {outPath} (Unicode {version})");
return 0;
